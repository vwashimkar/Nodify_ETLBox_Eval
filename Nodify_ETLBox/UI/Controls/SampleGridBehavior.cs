using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using EtlDesigner.UI.ViewModels;

namespace EtlDesigner.UI.Controls;

/// <summary>
/// Attached properties for the ParseValue sample grid, so the window has no code-behind:
/// <list type="bullet">
/// <item><c>SelectionCommand</c> receives a <see cref="GridSelection"/> whenever the selected cells change.</item>
/// <item><c>SourceColumn</c> gives that column's header the style <c>SourceColumnHeaderStyle</c>.</item>
/// <item><c>FocusRow</c> selects that row's first data cell and scrolls to it (0-based, -1 = none).</item>
/// </list>
/// The first column "#" is the row number and is never reported as a selected column.
/// </summary>
public static class SampleGridBehavior
{
    private const string RowNumberColumn = "#";

    public static readonly DependencyProperty SelectionCommandProperty = DependencyProperty.RegisterAttached(
        "SelectionCommand", typeof(ICommand), typeof(SampleGridBehavior), new PropertyMetadata(null, OnSelectionCommandChanged));

    public static readonly DependencyProperty SourceColumnProperty = DependencyProperty.RegisterAttached(
        "SourceColumn", typeof(string), typeof(SampleGridBehavior), new PropertyMetadata(null, (d, _) => MarkSourceColumn(d as DataGrid)));

    public static readonly DependencyProperty FocusRowProperty = DependencyProperty.RegisterAttached(
        "FocusRow", typeof(int), typeof(SampleGridBehavior), new PropertyMetadata(-1, OnFocusRowChanged));

    public static ICommand? GetSelectionCommand(DependencyObject d) => (ICommand?)d.GetValue(SelectionCommandProperty);

    public static void SetSelectionCommand(DependencyObject d, ICommand? value) => d.SetValue(SelectionCommandProperty, value);

    public static string? GetSourceColumn(DependencyObject d) => (string?)d.GetValue(SourceColumnProperty);

    public static void SetSourceColumn(DependencyObject d, string? value) => d.SetValue(SourceColumnProperty, value);

    public static int GetFocusRow(DependencyObject d) => (int)d.GetValue(FocusRowProperty);

    public static void SetFocusRow(DependencyObject d, int value) => d.SetValue(FocusRowProperty, value);

    private static void OnSelectionCommandChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not DataGrid grid)
        {
            return;
        }

        grid.SelectedCellsChanged -= OnSelectedCellsChanged;
        grid.CurrentCellChanged -= OnCurrentCellChanged;
        grid.AutoGeneratedColumns -= OnAutoGeneratedColumns;
        if (e.NewValue is not null)
        {
            grid.SelectedCellsChanged += OnSelectedCellsChanged;
            grid.CurrentCellChanged += OnCurrentCellChanged;
            grid.AutoGeneratedColumns += OnAutoGeneratedColumns;
        }
    }

    private static void OnSelectedCellsChanged(object sender, SelectedCellsChangedEventArgs e) => Report((DataGrid)sender);

    private static void OnCurrentCellChanged(object? sender, EventArgs e) => Report((DataGrid)sender!);

    private static void OnAutoGeneratedColumns(object? sender, EventArgs e) => MarkSourceColumn(sender as DataGrid);

    private static void Report(DataGrid grid)
    {
        var command = GetSelectionCommand(grid);
        if (command is null)
        {
            return;
        }

        var cells = grid.SelectedCells.Select(c => ToCell(grid, c)).OfType<GridCell>().ToList();
        var selection = new GridSelection(cells, ToCell(grid, grid.CurrentCell));
        if (command.CanExecute(selection))
        {
            command.Execute(selection);
        }
    }

    private static GridCell? ToCell(DataGrid grid, DataGridCellInfo info)
    {
        var column = ColumnName(info.Column);
        if (info.Item is null || column is null || column == RowNumberColumn && info.Column.DisplayIndex == 0)
        {
            return null;
        }

        var row = grid.Items.IndexOf(info.Item);
        return row < 0 ? null : new GridCell(row, column);
    }

    private static string? ColumnName(DataGridColumn? column)
        => column is null ? null : string.IsNullOrEmpty(column.SortMemberPath) ? column.Header as string : column.SortMemberPath;

    private static void MarkSourceColumn(DataGrid? grid)
    {
        if (grid is null)
        {
            return;
        }

        var source = GetSourceColumn(grid);
        var style = grid.TryFindResource("SourceColumnHeaderStyle") as Style;
        foreach (var column in grid.Columns)
        {
            if (style is not null && !string.IsNullOrEmpty(source) && ColumnName(column) == source)
            {
                column.HeaderStyle = style;
            }
            else
            {
                // Clear, never set null: a local null is passed on to the header and hides the
                // implicit DataGridColumnHeader style (token colours), leaving the Windows default.
                column.ClearValue(DataGridColumn.HeaderStyleProperty);
            }
        }
    }

    private static void OnFocusRowChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not DataGrid grid || e.NewValue is not int row || row < 0 || row >= grid.Items.Count)
        {
            return;
        }

        var column = grid.Columns.FirstOrDefault(c => ColumnName(c) == GetSourceColumn(grid))
            ?? grid.Columns.FirstOrDefault(c => c.DisplayIndex > 0)
            ?? grid.Columns.FirstOrDefault();
        if (column is null)
        {
            return;
        }

        var item = grid.Items[row];
        var cell = new DataGridCellInfo(item, column);
        grid.SelectedCells.Clear();
        grid.SelectedCells.Add(cell);
        grid.CurrentCell = cell;
        grid.ScrollIntoView(item, column);
    }
}
